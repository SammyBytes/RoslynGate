import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const check = process.argv.includes("--check");

const toolsDoc = readJson("contracts/schema/tools.json");
const responses = readJson("contracts/schema/responses.json");

const outputs = new Map([
  [
    "products/typescript/src/generated/tools.ts",
    renderTools(toolsDoc.tools)
  ],
  [
    "products/typescript/src/generated/responses.ts",
    renderTypeScriptResponses(responses.$defs)
  ],
  [
    "src/RoslynGate.Mcp/Generated/Contracts.g.cs",
    renderCSharpResponses(responses.$defs)
  ]
]);

let failed = false;
for (const [relative, content] of outputs) {
  const file = path.join(root, relative);
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (current === content) continue;
  if (check) {
    process.stderr.write(`contracts: ${relative} is out of date\n`);
    failed = true;
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    process.stdout.write(`contracts: wrote ${relative}\n`);
  }
}

if (failed) {
  process.stderr.write("contracts: run npm run contracts:generate\n");
  process.exit(1);
}

function readJson(relative) {
  return JSON.parse(fs.readFileSync(path.join(root, relative), "utf8"));
}

function renderTools(tools) {
  return `// Generated by scripts/contracts/generate.mjs. Do not edit.
export type JsonSchema = Record<string, unknown>;

export interface ToolAnnotations {
  readonly idempotentHint: boolean;
  readonly openWorldHint: boolean;
  readonly readOnlyHint: boolean;
}

export interface ToolDefinition {
  readonly name: string;
  readonly description: string;
  readonly annotations: ToolAnnotations;
  readonly inputSchema: JsonSchema;
}

export const TOOL_DEFINITIONS = ${JSON.stringify(tools, null, 2)} as const satisfies readonly ToolDefinition[];
`;
}

function renderTypeScriptResponses(defs) {
  const lines = [
    "// Generated by scripts/contracts/generate.mjs. Do not edit.",
    ""
  ];
  for (const [name, schema] of Object.entries(defs)) {
    lines.push(`export type ${pascal(name)} = ${tsType(schema, defs)};`, "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

function tsType(schema, defs) {
  if (!schema) return "unknown";
  if (schema.$ref) return pascal(schema.$ref.split("/").pop());
  if (schema.oneOf) {
    return schema.oneOf.map((item) => tsType(item, defs)).join(" | ");
  }
  if (schema.type === "null") return "null";
  if (Array.isArray(schema.type)) {
    return schema.type.map((item) => tsType({ ...schema, type: item }, defs)).join(" | ");
  }
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      if (schema.prefixItems) {
        return `[${schema.prefixItems.map((item) => tsType(item, defs)).join(", ")}]`;
      }
      return `Array<${tsType(schema.items ?? {}, defs)}>`;
    case "object":
      if (schema.properties) {
        const required = new Set(schema.required ?? []);
        const properties = Object.entries(schema.properties).map(([key, value]) => {
          const optional = required.has(key) ? "" : "?";
          return `${JSON.stringify(key)}${optional}: ${tsType(value, defs)};`;
        });
        return `{ ${properties.join(" ")} }`;
      }
      return "Record<string, unknown>";
    default:
      return "unknown";
  }
}

function renderCSharpResponses(defs) {
  const body = [];
  for (const [name, schema] of Object.entries(defs)) {
    if (schema.type === "object" && schema.properties) {
      body.push(renderRecord(csName(name), schema, defs));
    } else if (schema.type === "array") {
      body.push(`public sealed class ${csName(name)} : List<JsonElement>;`);
    }
  }

  return `// Generated by scripts/contracts/generate.mjs. Do not edit.
#nullable enable

using System.Collections.Generic;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace RoslynGate.Mcp.Generated;

${body.join("\n\n")}
`;
}

function renderRecord(name, schema, defs) {
  const required = new Set(schema.required ?? []);
  const properties = Object.entries(schema.properties).map(([key, value]) => {
    const optional = !required.has(key);
    const modifier = optional ? "" : "required ";
    return `    [JsonPropertyName("${key}")]
    public ${modifier}${csType(value, defs, optional)} ${pascal(key)} { get; init; }`;
  });
  return `public sealed record ${name}
{
${properties.join("\n\n")}
}`;
}

function csType(schema, defs, optional) {
  if (!schema) return optional ? "JsonElement?" : "JsonElement";
  if (schema.$ref) {
    const target = defs[schema.$ref.split("/").pop()];
    if (target?.type === "array") return "List<JsonElement>";
    if (target?.oneOf) return "JsonElement";
    const type = csName(schema.$ref.split("/").pop());
    return optional ? `${type}?` : type;
  }
  if (schema.oneOf) {
    const ref = schema.oneOf.find((item) => item.$ref);
    if (ref) {
      const type = csName(ref.$ref.split("/").pop());
      return optional || schema.oneOf.some((item) => item.type === "null") ? `${type}?` : type;
    }
    return "JsonElement";
  }
  if (Array.isArray(schema.type)) {
    const nonNull = schema.type.find((item) => item !== "null");
    return csType({ ...schema, type: nonNull }, defs, true);
  }
  switch (schema.type) {
    case "string":
      return optional ? "string?" : "string";
    case "integer":
      return optional ? "int?" : "int";
    case "boolean":
      return optional ? "bool?" : "bool";
    case "array":
      if (schema.prefixItems) return optional ? "List<JsonElement>?" : "List<JsonElement>";
      return optional
        ? `List<${csType(schema.items ?? {}, defs, false)}>?`
        : `List<${csType(schema.items ?? {}, defs, false)}>`;
    case "object":
      return optional ? "Dictionary<string, JsonElement>?" : "Dictionary<string, JsonElement>";
    case "null":
      return "JsonElement?";
    default:
      return "JsonElement";
  }
}

function csName(value) {
  return `${pascal(value)}Contract`;
}

function pascal(value) {
  return value
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}
